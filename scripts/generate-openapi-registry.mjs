// Transforms src/apis/api.ts → src/server/openapi-registry.ts
// Converts type-only imports to value imports and builds a route registry array.
// Run from app directory: node ../../scripts/generate-openapi-registry.mjs

import { readFileSync, writeFileSync } from "fs";
import { resolve } from "path";

// process.cwd() is the app root when invoked via npm scripts
const appRoot = process.cwd();
const apiTsPath = resolve(appRoot, "src/apis/api.ts");
const outputPath = resolve(appRoot, "src/server/openapi-registry.ts");

const content = readFileSync(apiTsPath, "utf-8");

// Extract: import type { XSchema } from "src/pages/api/..."
const importMap = new Map();
const importRegex = /^import type \{ (\w+) \} from "(src\/pages\/api\/[^"]+)";$/gm;
let match;
while ((match = importRegex.exec(content)) !== null) {
  importMap.set(match[1], match[2]);
}

// Extract: fromTypeboxRoute<typeof XSchema>("METHOD", "URL")
const routeEntries = [];
const routeRegex = /fromTypeboxRoute<typeof (\w+)>\("([A-Z]+)", "([^"]+)"\)/g;
while ((match = routeRegex.exec(content)) !== null) {
  routeEntries.push({ schemaName: match[1], method: match[2], url: match[3] });
}

const usedSchemas = new Set(routeEntries.map((r) => r.schemaName));

const importLines = [...importMap.entries()]
  .filter(([name]) => usedSchemas.has(name))
  .map(([name, path]) => `import { ${name} } from "${path}";`)
  .join("\n");

const routesArray = routeEntries
  .map(({ schemaName, method, url }) => `  { schema: ${schemaName}, method: "${method}", url: "${url}" },`)
  .join("\n");

const output = `/* eslint-disable */
// AUTO-GENERATED by scripts/generate-openapi-registry.mjs — do not edit manually
// Re-run after: npm run client

${importLines}

import type { RouteEntry } from "@scow/lib-web/build/utils/typebox-to-openapi";

export const openapiRoutes: RouteEntry[] = [
${routesArray}
];
`;

writeFileSync(outputPath, output);
console.log(`Generated ${routeEntries.length} routes → ${outputPath}`);
